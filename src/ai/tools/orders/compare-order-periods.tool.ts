import { Injectable } from '@nestjs/common';
import { AiTool } from '../ai-tool.interface';
import { OrdersStatisticsService } from '../../../orders/services/orders-statistics.service';
import { CompareOrderPeriodsSchema } from './dto/compare-order-periods.schema';

@Injectable()
export class CompareOrderPeriodsTool implements AiTool {
  readonly name = 'compare_order_periods';
  readonly schema = CompareOrderPeriodsSchema;

  readonly description = `
Сравнивает статистику заказов за два указанных периода.

Используй этот инструмент, когда пользователь:
- просит сравнить количество заказов за два периода;
- просит сравнить продажи за два периода;
- хочет узнать рост или падение показателей;
- просит сравнить текущий период с предыдущим;
- просит сравнить два конкретных календарных периода;
- хочет сравнить сумму заказов, сумму выплат или количество заказанных товаров.

period1 — первый период, который указал пользователь.
period2 — второй период, который указал пользователь.

Не меняй порядок периодов.
Если пользователь сказал "сравни август с июлем",
то август должен быть period1, а июль — period2.

Инструмент возвращает статистику отдельно для каждого периода:
- ordersCount — количество заказов;
- totalQuantity — количество заказанных товаров;
- totalPrice — общая сумма заказов;
- totalPayout — общая сумма выплат.

После получения результата самостоятельно сравни показатели
period1 и period2 и сформулируй вывод для пользователя.

Для процентного изменения используй формулу:

((значение period1 - значение period2) / значение period2) * 100

Положительное значение означает рост period1 относительно period2.
Отрицательное значение означает снижение period1 относительно period2.

Если значение period2 равно 0,
не рассчитывай процентное изменение.
В этом случае сравни показатели по абсолютным значениям.

Периоды могут иметь разную продолжительность,
если пользователь явно указал такие периоды.

Если пользователь просит сравнить относительные периоды
без явной продолжительности, используй периоды одинаковой
продолжительности.

Дата:
- Используй текущую дату и время из system message как источник истины.
- "сегодня" — текущий календарный день.
- "вчера" — предыдущий календарный день.
- "позавчера" — два календарных дня назад.
- "завтра" — следующий календарный день.

Для календарных периодов используй полуоткрытый интервал [dateFrom, dateTo):
- dateFrom включается в период;
- dateTo не включается в период;
- для одного календарного дня dateFrom — начало дня,
  dateTo — начало следующего дня;
- не используй 23:59:59, если можно указать начало следующего дня.

Если необходимые даты невозможно определить из запроса пользователя
или контекста диалога, не вызывай инструмент и запроси уточнение.

Дополнительные фильтры marketplaceTitle, warehouseTitle
и warehouseType передавай только тогда, когда они указаны
или однозначно определяются из запроса пользователя.

Никогда не передавай внутренние ID маркетплейсов или складов.
Backend самостоятельно определяет соответствующие ID
по переданным названиям.

При формировании ответа используй только показатели,
относящиеся к вопросу пользователя.

Если пользователь спрашивает только количество заказов,
используй ordersCount.

Если пользователь спрашивает количество товаров,
используй totalQuantity.

Если пользователь спрашивает сумму заказов,
используй totalPrice.

Если пользователь спрашивает сумму выплат,
используй totalPayout.

Не выводи остальные показатели без необходимости.
`;

  readonly parameters = CompareOrderPeriodsSchema;

  constructor(private readonly ordersStatisticsService: OrdersStatisticsService) {}

  async execute(args: unknown) {
    const validatedArgs = CompareOrderPeriodsSchema.parse(args);

    return this.ordersStatisticsService.comparePeriods(validatedArgs);
  }
}
