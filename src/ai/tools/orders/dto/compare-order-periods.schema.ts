import { z } from 'zod';
import { MarketplaceTitleSchema } from './marketplace-title.schema';

export const CompareOrderPeriodsSchema = z.object({
  period1DateFrom: z.iso.datetime({ local: true, offset: true }).describe(`
Начало первого периода в формате ISO 8601.

Дата и время включаются в период.

Для календарного дня указывай начало этого дня:
26 августа → 2026-08-26T00:00:00

period1 — первый период, который указал пользователь.
Не меняй порядок периодов.
`),

  period1DateTo: z.iso.datetime({ local: true, offset: true }).describe(`
Исключающая граница конца первого периода в формате ISO 8601.

Дата и время, равное period1DateTo, не входит в период.

Для календарного дня указывай начало следующего дня:
26 августа → 2026-08-27T00:00:00

Не используй 23:59:59, если можно указать начало следующего дня.
`),

  period2DateFrom: z.iso.datetime({ local: true, offset: true }).describe(`
Начало второго периода в формате ISO 8601.

Дата и время включаются в период.

Для календарного дня указывай начало этого дня:
25 августа → 2026-08-25T00:00:00

period2 — второй период, который указал пользователь.
Не меняй порядок периодов.
`),

  period2DateTo: z.iso.datetime({ local: true, offset: true }).describe(`
Исключающая граница конца второго периода в формате ISO 8601.

Дата и время, равное period2DateTo, не входит в период.

Для календарного дня указывай начало следующего дня:
25 августа → 2026-08-26T00:00:00

Не используй 23:59:59, если можно указать начало следующего дня.
`),

  article: z.string().optional().describe(`
Артикул товара.

Передавай артикул, который явно указал пользователь.
Не изменяй значение артикула и не придумывай его.

Примеры:
"артикул 12345" → "12345"
"по артикулу ABC-123" → "ABC-123"

Если пользователь не указал артикул, не передавай это поле.
`),

  marketplaceTitle: MarketplaceTitleSchema.optional().describe(`
Каноническое название маркетплейса.

Допустимые значения:
"Озон"
"WB"
"Yandex"
"Yandex Tamov"
"Ozon Tamov"

Нормализация названий:
"Ozon", "озон", "озоне" → "Озон"
"WB", "wb", "ВБ", "вб", "Wildberries", "Вайлдберриз", "Вайлдберис" → "WB"
"Yandex", "Яндекс", "Яндекс Маркет" → "Yandex"
"Yandex Tamov", "Яндекс Тамов" → "Yandex Tamov"
"Ozon Tamov", "Озон Тамов" → "Ozon Tamov"

Если пользователь не указал маркетплейс, не передавай это поле.
`),

  warehouseTitle: z.string().optional().describe(`
Название конкретного склада.

Передавай только название склада, которое пользователь явно указал.

Не придумывай название склада.

Если пользователь указал только тип склада
("FBO", "FBS", "наш склад", "склад маркетплейса" и т.п.),
не передавай warehouseTitle. В этом случае используй warehouseType.
`),

  warehouseType: z.enum(['FBO', 'FBS']).optional().describe(`
Тип склада.

FBO — склад маркетплейса.
FBS — собственный склад продавца.

Нормализация:
"наш склад" → "FBS"
"наши склады" → "FBS"
"собственный склад" → "FBS"
"склад продавца" → "FBS"
"FBS" → "FBS"

"склад Ozon" → "FBO"
"склад WB" → "FBO"
"склад маркетплейса" → "FBO"
"FBO" → "FBO"

Если пользователь явно указал конкретное название склада,
используй warehouseTitle.

Если тип склада невозможно однозначно определить,
не передавай warehouseType.
`)
});

export type CompareOrderPeriodsArgs = z.infer<typeof CompareOrderPeriodsSchema>;
