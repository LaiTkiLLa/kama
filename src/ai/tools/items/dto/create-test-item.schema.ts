import { z } from 'zod';

/** Положительное число в виде строки: "100", "145.5". Без единиц измерения и запятых. */
const numericString = z
  .string()
  .trim()
  .regex(/^\d+(\.\d+)?$/, 'Ожидается положительное число, например "145.5"')
  .refine(value => Number(value) > 0, 'Значение должно быть больше 0');

export const CreateTestItemSchema = z.object({
  lengthMasterBox: numericString.describe(`
Длина мастер короба в сантиметрах.

Передавай только числовое значение без единицы измерения.
Значение может быть дробным, разделитель дробной части — точка.

Примеры:
"длина 145.5 см" → "145.5"
"длина 100 см" → "100"

Значение может быть дробным.
`),

  widthMasterBox: numericString.describe(`
Ширина мастер короба в сантиметрах.

Передавай только числовое значение без единицы измерения.

Примеры:
"ширина 56 см" → "56"
"ширина 42.5 см" → "42.5"

Значение может быть дробным.
`),

  heightMasterBox: numericString.describe(`
Высота мастер короба в сантиметрах.

Передавай только числовое значение без единицы измерения.

Примеры:
"высота 16.5 см" → "16.5"
"высота 20 см" → "20"

Значение может быть дробным.
`),

  weightMasterBox: numericString.describe(`
Вес мастер короба в килограммах.

Передавай только числовое значение без единицы измерения.

Примеры:
"вес 2 кг" → "2"
"вес 1.5 кг" → "1.5"

Значение может быть дробным.
`),

  category: z.string().trim().min(1).describe(`
Категория товара.

Передавай название категории, указанное пользователем.
Не придумывай категорию и не изменяй её значение.
`),
  title: z.string().trim().min(1).optional().describe(`
Наименование товара.

Передавай наименование товара, указанное пользователем.
Не придумывай и не изменяй наименование.

Поле необязательное.
Если пользователь не указал наименование товара, не передавай это поле.
`),
  costInYuan: z.number().describe(`
  Себестоимость товара в юанях.
  
  Передавай числовое значение без единицы измерения.
  Значение может быть дробным.
  
  Примеры:
  "себестоимость 100 юаней" → 100
  "себестоимость 145.5 юаней" → 145.5
  `),

  costInYuanWhite: z.number().describe(`
  Себестоимость товара в юанях с учетом налогов.
  
  Передавай числовое значение без единицы измерения.
  Значение может быть дробным.
  
  Примеры:
  "себестоимость с налогами 110 юаней" → 110
  "себестоимость с налогами 145.5 юаней" → 145.5
  `),

  costCalculationType: z.enum(['по таможенной стоимости', 'по весу']).describe(`
  Тип расчета таможенной стоимости.
  
  Допустимые значения:
  - "по таможенной стоимости"
  - "по весу"
  
  Передавай только одно из указанных значений.
  Не придумывай другие варианты и не изменяй значение.
  `),

  calculationType: z.enum(['В белую', 'В серую']).describe(`
  Тип расчета товара.
  
  Допустимые значения:
  - "В белую"
  - "В серую"
  
  Передавай только одно из указанных значений.
  Не придумывай другие варианты и не изменяй значение.
  `),

  downloadCalculationMethod: z.enum([
    'по объему (64)',
    'по весу (64)',
    'по объему (25)',
    'по весу (25)',
    'сборный груз',
    'по объёму (80)',
    'по весу (80)',
    'по объёму (100)',
    'по весу (100)'
  ]).describe(`
  Метод расчета загрузки товара.
  
  Допустимые значения:
  - "по объему (64)"
  - "по весу (64)"
  - "по объему (25)"
  - "по весу (25)"
  - "сборный груз"
  - "по объёму (80)"
  - "по весу (80)"
  - "по объёму (100)"
  - "по весу (100)"
  
  Передавай только одно из указанных значений.
  Не придумывай другие варианты и не изменяй значение.
  `),
  multiplicity: numericString.describe(`
Кратность товара.

Количество единиц товара, которое находится в одном мастер-коробе.

Передавай только числовое значение без единицы измерения.
Значение может быть дробным, разделитель дробной части — точка.

Примеры:
"в коробе 20 штук" → "20"
"по 12 товаров в коробе" → "12"
"кратность 24" → "24"
`)
});

export type CreateTestItemArgs = z.infer<typeof CreateTestItemSchema>;
